import { computeDropoff } from '../lib/engine.js'
import {
  VOUCHERS,
  HOME_HUB_ID,
  initialHubLoads,
  ACCOUNT_TYPES,
} from '../data/catalog.js'

export const STORAGE_KEY = 'greenloop-state-v3'

function emptyAccount(accountType) {
  const acct = ACCOUNT_TYPES[accountType] || ACCOUNT_TYPES.residence
  return {
    tokenBalance: 0,
    transactions: [],
    redeemedVouchers: [],
    maintenanceFee: acct.feeAmount,
    feeOffsetRm: 0,
    feeOffsets: [],
  }
}

const seedHubs = () => [
  { id: 'HUB-000000001', name: 'Elm Avenue Hub (Manual Demo)', location: 'Jalan Elm, City of Elmina', mode: 'manual', registeredAt: Date.now() - 30 * 86400000 },
  { id: 'HUB-000000002', name: 'Central Hub', location: 'Greenview Township Central', mode: 'auto', registeredAt: Date.now() - 25 * 86400000 },
  { id: 'HUB-000000003', name: 'Northgate Point', location: 'Northgate Boulevard', mode: 'auto', registeredAt: Date.now() - 20 * 86400000 },
  { id: 'HUB-000000004', name: 'Lakeside Node', location: 'Lakeside Drive', mode: 'auto', registeredAt: Date.now() - 15 * 86400000 },
]

export function initialState() {
  return {
    auth: { session: null, users: [] }, // session: {role,id,name,email,address,avatar}
    hubs: seedHubs(),
    accountType: 'residence',
    accounts: {}, // keyed by user id (USER-… / TENT-…)
    opsTransactions: [],
    hubLoads: initialHubLoads(),
  }
}

let seq = 0
function uid(prefix) {
  seq += 1
  return `${prefix}-${Date.now()}-${seq}`
}

function makeVoucherCode() {
  const chars = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789'
  const block = () =>
    Array.from({ length: 4 }, () => chars[Math.floor(Math.random() * chars.length)]).join('')
  return `GL-${block()}-${block()}`
}

// The account belonging to whoever is logged in (user/tenant), or the legacy
// persona key for ops/seed flows.
function activeKey(state) {
  return state.auth?.session?.id || state.accountType
}

function updateActive(state, updater) {
  const key = activeKey(state)
  const cur =
    state.accounts[key] ||
    emptyAccount(state.auth?.session?.role === 'tenant' ? 'tenant' : state.accountType)
  return { ...state, accounts: { ...state.accounts, [key]: updater(cur) } }
}

export function reducer(rawState, action) {
  // Normalise older persisted shapes.
  const base = initialState()
  const state = {
    ...base,
    ...rawState,
    auth: rawState.auth || base.auth,
    hubs: rawState.hubs?.length ? rawState.hubs : base.hubs,
    accounts: rawState.accounts || {},
  }

  switch (action.type) {
    case 'REGISTER': {
      const user = {
        role: action.role, // 'user' | 'tenant'
        id: action.id, // USER-000000001 / TENT-000000001 (generated by caller)
        name: action.name,
        address: action.address,
        email: action.email,
        password: action.password,
        avatar: null,
      }
      const { password, ...pub } = user
      const accountType = user.role === 'tenant' ? 'tenant' : 'residence'
      return {
        ...state,
        accountType,
        auth: { ...state.auth, users: [...state.auth.users, user], session: pub },
        accounts: { ...state.accounts, [user.id]: emptyAccount(accountType) },
      }
    }

    case 'LOGIN': {
      if (action.ops) {
        return {
          ...state,
          auth: {
            ...state.auth,
            session: {
              role: 'ops', id: 'synkosys', name: 'Synkosys Operations',
              email: 'ops@synkosys.my', address: 'Operations Centre', avatar: null,
            },
          },
        }
      }
      const u = state.auth.users.find((x) => x.id === action.id)
      if (!u) return state
      const { password, ...pub } = u
      const accountType = u.role === 'tenant' ? 'tenant' : 'residence'
      const accounts = state.accounts[u.id]
        ? state.accounts
        : { ...state.accounts, [u.id]: emptyAccount(accountType) }
      return { ...state, accountType, accounts, auth: { ...state.auth, session: pub } }
    }

    case 'LOGOUT':
      return { ...state, auth: { ...state.auth, session: null } }

    case 'UPDATE_PROFILE': {
      const id = state.auth.session.id
      const users = state.auth.users.map((u) =>
        u.id === id
          ? { ...u, ...action.patch, password: action.patch.password || u.password }
          : u
      )
      const { password, ...pub } = action.patch
      return {
        ...state,
        auth: { ...state.auth, users, session: { ...state.auth.session, ...pub } },
      }
    }

    case 'REGISTER_HUB': {
      const id = `HUB-${String(state.hubs.length + 1).padStart(9, '0')}`
      return {
        ...state,
        hubs: [
          ...state.hubs,
          { id, name: action.name, location: action.location, mode: 'auto', registeredAt: Date.now() },
        ],
      }
    }

    case 'DROP_OFF': {
      const result = computeDropoff(action.itemId, action.quantity)
      if (result.quantity <= 0) return state
      const hubId = action.hubId || HOME_HUB_ID
      const tx = { id: uid('tx'), timestamp: action.timestamp || Date.now(), hubId, ...result }
      const next = updateActive(state, (a) => ({
        ...a,
        tokenBalance: a.tokenBalance + result.tokensAwarded,
        transactions: [tx, ...a.transactions],
      }))
      const hubLoads = { ...next.hubLoads }
      hubLoads[hubId] = (hubLoads[hubId] || 0) + result.totalWeight
      return { ...next, opsTransactions: [tx, ...next.opsTransactions], hubLoads }
    }

    // Township-only drop (Smart Bin simulation in the Operations view).
    case 'OPS_DROP': {
      const result = computeDropoff(action.itemId, action.quantity)
      if (result.quantity <= 0) return state
      const tx = {
        id: uid('tx'),
        timestamp: action.timestamp || Date.now(),
        hubId: action.hubId,
        ...result,
      }
      const hubLoads = { ...state.hubLoads }
      hubLoads[action.hubId] = (hubLoads[action.hubId] || 0) + result.totalWeight
      return { ...state, opsTransactions: [tx, ...state.opsTransactions], hubLoads }
    }

    case 'REDEEM_VOUCHER': {
      const voucher = VOUCHERS.find((v) => v.id === action.voucherId)
      if (!voucher) return state
      const a = state.accounts[activeKey(state)]
      if (!a || a.tokenBalance < voucher.costTokens) return state
      return updateActive(state, (acc) => ({
        ...acc,
        tokenBalance: acc.tokenBalance - voucher.costTokens,
        redeemedVouchers: [
          {
            id: uid('rv'), voucherId: voucher.id, name: voucher.name, value: voucher.value,
            costTokens: voucher.costTokens, emoji: voucher.emoji,
            code: action.code || makeVoucherCode(), used: false,
            timestamp: action.timestamp || Date.now(),
          },
          ...acc.redeemedVouchers,
        ],
      }))
    }

    case 'MARK_VOUCHER_USED': {
      return updateActive(state, (a) => ({
        ...a,
        redeemedVouchers: a.redeemedVouchers.map((r) =>
          r.id === action.id ? { ...r, used: true, usedAt: action.timestamp || Date.now() } : r
        ),
      }))
    }

    case 'OFFSET_FEE': {
      const a = state.accounts[activeKey(state)]
      if (!a) return state
      const tokens = Math.min(action.tokens, a.tokenBalance)
      if (tokens <= 0) return state
      const rm = tokens * action.rmPerToken
      const remainingFee = a.maintenanceFee - a.feeOffsetRm
      const applied = Math.min(rm, remainingFee)
      if (applied <= 0) return state
      const tokensUsed = Math.ceil(applied / action.rmPerToken)
      return updateActive(state, (acc) => ({
        ...acc,
        tokenBalance: acc.tokenBalance - tokensUsed,
        feeOffsetRm: Math.min(acc.maintenanceFee, acc.feeOffsetRm + applied),
        feeOffsets: [
          { id: uid('fo'), rm: Math.round(applied * 100) / 100, tokensUsed, timestamp: action.timestamp || Date.now() },
          ...acc.feeOffsets,
        ],
      }))
    }

    case 'SET_ACCOUNT': {
      if (!ACCOUNT_TYPES[action.accountType] || action.accountType === state.accountType) return state
      return { ...state, accountType: action.accountType }
    }

    case 'SEED': {
      const txs = action.transactions
      const fresh = initialState()
      const role = state.auth?.session?.role
      const key = state.auth?.session?.id
      const seedTx = role === 'tenant' ? action.tenantTx || [] : action.residenceTx || []
      return {
        ...fresh,
        auth: state.auth,
        hubs: state.hubs,
        accountType: role === 'tenant' ? 'tenant' : 'residence',
        opsTransactions: txs,
        accounts: key ? { [key]: seedAccount(role === 'tenant' ? 'tenant' : 'residence', seedTx) } : {},
      }
    }

    case 'RESET':
      return { ...initialState(), auth: state.auth, hubs: state.hubs }

    case 'HYDRATE':
      return { ...initialState(), ...action.state }

    default:
      return state
  }
}

function seedAccount(accountType, txs) {
  const a = emptyAccount(accountType)
  const withIds = txs.map((t, i) => ({ id: `seed-${accountType}-${i}`, timestamp: Date.now() - i * 86400000, ...t }))
  return {
    ...a,
    transactions: withIds,
    tokenBalance: withIds.reduce((s, t) => s + t.tokensAwarded, 0),
  }
}